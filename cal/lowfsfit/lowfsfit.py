"""
Functions to locate the pupil in a lowfs image

1176785
Given:
  1) a list of FSM strain gauge positions (X, Y) in on-sky milliarcseconds,
     along the EXCAM sensor axes, and
  2) a set of one or more LOCAM summed frames collected at each FSM position,

lowfsfit computes a list of (row, col) positions of the center of the pupil
  on LOCAM for each FSM position.

"""
import os

from astropy.io import fits
from cal.pr.util.image_registration import cross_correlation

from cal.util import check
from cal.util.loadyaml import loadyaml

LOCAL_PATH = os.path.dirname(os.path.abspath(__file__))
DEFAULT_CONFIG_FN = os.path.join(LOCAL_PATH, 'config_files', 'lowfsfit_parms.yaml')


def locate_img(list_moving_image, reference_image_fn, config_fn=DEFAULT_CONFIG_FN):
    """
    compute the (row, col) position of each moving_image
    by image correlation with the reference image.

    All images, reference and moving, must be the same array size

    All filenames may be absolute or relative paths.  If relative, they will be
    relative to the current working directory, not to any particular location
    in Calibration.  Note that if config_fn is not specified, the function
    will call a YAML file delivered with the repository which contains a
    default set of empirically-good parameters from our testing.

    Parameters
    ----------
    list_moving_image : list of 2-d real arrays
        Intensity LOCAM images to be registered, bias and dark subtracted

    reference_image_fn : str
        Filename to a fits file containing a reference LOWFS image in the primary HDU,
        The reference image must be the same shape as the images in imageList.
        The reference image is a measured or modeled LOCAM image with the pupil
        at the desired location on the camera, typically the center of the camera's
        active field, with bias and dark removed.
        The offsets between the "moving" images in imageList and the reference
        are the XY offsets used to create the transform matrix. The default
        reference image was generated by cgisim model.

    config_fn : str
        filename, with absolute or relative path, to config yaml file

        The yaml file contains these parameters:
        upsample_factor : scalar

    Returns
    -------
    list_row_col : list of [row, col] floats
        each [row, col] is the shift of the moving image to the
        reference image.
    """

    # Validate inputs
    # check list_moving_image is a list
    if not isinstance(list_moving_image, list):
        raise TypeError('list_moving_image must be a list')

    check.string(reference_image_fn, 'reference_image_fn', TypeError)
    reference_image = fits.getdata(os.path.expandvars(reference_image_fn))
    
    # check all images are real values
    check.real_array(reference_image, 'reference_image', TypeError)
    for img in list_moving_image:
        check.real_array(img, 'list_moving_image', TypeError)

    # check all images are 2-d
    check.twoD_array(reference_image, 'reference_image', TypeError)
    for img in list_moving_image:
        check.twoD_array(img, 'list_moving_image', TypeError)

    # check all images are same size
    for img in list_moving_image:
        if img.shape != reference_image.shape:
            raise TypeError('each moving img must have same shape as ref img')

    # loadyaml checks config file exists and it is yaml
    params = loadyaml(config_fn)
    
    # check params contains required keywords
    if not 'upsample_factor' in params:
        raise ValueError('params yaml does not include upsample_factor')

    # upsample_factor is a positive integer
    upsample_factor = params['upsample_factor']
    check.positive_scalar_integer(upsample_factor, 'upsample_factor', TypeError)
    
    # do the cross-correlation for each
    list_retval = [
        cross_correlation(reference_image, moving_image,
                          upsample_factor=upsample_factor)
        for moving_image in list_moving_image
    ]

    # row, col is retval. Re-order to xy. Multiply by -1 to make it 
    # moving image relative to the reference image
    xyOffsetList = [retval[::-1]*-1 for retval in list_retval]

    return xyOffsetList
